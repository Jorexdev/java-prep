package base.streams.ejemplosercicios.facil;

/*
    STREAMS - Ejercicios Easy

    Ejercicios de nivel básico para practicar las operaciones fundamentales de Streams:
    filter, map, reduce, collect, sorted, groupingBy, anyMatch, findFirst...

    Las soluciones están en: easy/soluciones/Ejercicio1.java ... Ejercicio10.java
*/
public class Enunciado {

    /*
        Ejercicio 1 - Filtrado y conteo

        Dada una lista de personas con sus edades, usa Streams para contar cuántas
        personas tienen más de 18 años.
    */

    /*
        Ejercicio 2 - Transformación y listado

        Dada una lista de cadenas, transforma todas las palabras a mayúsculas
        y recoge los resultados en una nueva lista.
    */

    /*
        Ejercicio 3 - Suma y reducción

        Dada una lista de números enteros, calcula la suma de todos los números pares
        usando Streams.
    */

    /*
        Ejercicio 4 - Mapeo y filtrado

        Dada una lista de objetos Producto con nombre y precio, obtén una lista solo
        con los nombres de productos cuyo precio sea mayor a 100.
    */

    /*
        Ejercicio 5 - Agrupamiento

        Dada una lista de personas con su ciudad de residencia, agrupa las personas
        por ciudad y cuenta cuántas personas hay en cada una.
    */

    /*
        Ejercicio 6 - Ordenamiento

        Dada una lista de empleados con nombre y salario, ordena la lista por salario
        en orden descendente y muestra los primeros 5 empleados mejor pagados.
    */

    /*
        Ejercicio 7 - Flattening (aplanar)

        Dada una lista de objetos Persona con listas de habilidades, genera una lista
        plana de todas las habilidades distintas sin repetir ninguna.
    */

    /*
        Ejercicio 8 - Encontrar máximo

        Dada una lista de estudiantes con sus notas, encuentra al estudiante con
        la nota más alta usando Streams.
    */

    /*
        Ejercicio 9 - Validación

        Dada una lista de strings, verifica si todos los elementos tienen longitud
        mayor que 3.
    */

    /*
        Ejercicio 10 - Construcción de mapa

        Dada una lista de objetos Persona con nombre y edad, construye un
        Map<String, Integer> donde la clave sea el nombre y el valor la edad.
    */
}
